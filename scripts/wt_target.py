#!/usr/bin/env python3
"""worktree 构建产物落 E: 盘的本机策略工具（D 盘只放代码）。

用法：
  python scripts/wt_target.py                 # 对当前 worktree 幂等生成
  python scripts/wt_target.py --all           # 对 `git worktree list` 全部幂等生成
  python scripts/wt_target.py --status        # 只报告，不写
  python scripts/wt_target.py --self-test

背景（docs/BUILD-PERF.md §3）：
  主 worktree 手工放了一份 `.cargo/config.toml`（`target-dir = E:/cargo-target/trit`），
  但它列在 `.git/info/exclude` 不入库 —— `git worktree add` 出来的 worktree 全都
  没有它，构建产物写回 D 盘直到写满。本工具把这份覆盖文件补到每个 worktree，
  且彼此独立目录（共享 target 会带来 cargo 锁竞争与指纹互相失效，不共享）。

生效条件（全部满足才写，缺一跳过）：
  1) 策略根存在（默认 `E:/cargo-target`，`TRIT_TARGET_ROOT` 可覆盖）——没有该目录
     的环境（CI、其它机器）自动什么都不做；
  2) worktree 顶层有 `Cargo.toml`（只管 Rust 项目）；
  3) `.cargo/config.toml` 尚不存在（手工管理的（比如主 worktree）不覆盖）。

生成的文件列在 `.gitignore` 的 `.cargo/config.toml` 条目下，不会进 git status。
本机的 `.git/hooks/trit-hooks.py`（post-checkout）会在新建 worktree 时自动调用
同一逻辑；本脚本是可复制、可审计、可手动批量补齐的入库层。
"""

from __future__ import annotations

import os
import pathlib
import subprocess
import sys

MARKER = "# local policy: build artifacts on E:"


def target_root(env: dict | None = None) -> pathlib.Path:
    """策略根：默认 `E:/cargo-target`，`TRIT_TARGET_ROOT` 覆盖（self-test 用）。"""
    env = env if env is not None else os.environ
    return pathlib.Path(env.get("TRIT_TARGET_ROOT", "E:/cargo-target"))


def config_text(root: pathlib.Path, name: str) -> str:
    """生成 `.cargo/config.toml` 的内容（`\\n` 换行，UTF-8）。"""
    lines = [
        f"{MARKER} (generated by scripts/wt_target.py)",
        "# listed in .gitignore; not committed",
        "[build]",
        f'target-dir = "{(root / name).as_posix()}"',
        "",
    ]
    return "\n".join(lines)


def ensure(top: pathlib.Path, root: pathlib.Path) -> str:
    """对单个 worktree 幂等生成；返回 `written` / `exists` / `skip:<原因>`。"""
    if not root.is_dir():
        return "skip:no-target-root"
    if not (top / "Cargo.toml").is_file():
        return "skip:no-cargo-toml"
    cfg = top / ".cargo" / "config.toml"
    if cfg.exists():
        return "exists"
    cfg.parent.mkdir(parents=True, exist_ok=True)
    cfg.write_text(config_text(root, top.name), encoding="utf-8", newline="\n")
    return "written"


def worktree_roots(repo: pathlib.Path) -> list[pathlib.Path]:
    """`git worktree list` 的顶层路径（含主 worktree）。"""
    out = subprocess.run(
        ["git", "worktree", "list", "--porcelain"],
        cwd=repo, capture_output=True, text=True, encoding="utf-8", errors="replace",
        check=True,
    ).stdout
    tops = []
    for line in out.splitlines():
        if line.startswith("worktree "):
            tops.append(pathlib.Path(line[len("worktree "):]))
    return tops


def run(args: list[str], env: dict | None = None) -> int:
    root = target_root(env)
    if "--self-test" in args:
        return self_test()
    repo = pathlib.Path.cwd()
    if "--root" in args:
        repo = pathlib.Path(args[args.index("--root") + 1]).resolve()
    tops = worktree_roots(repo) if "--all" in args else [repo]
    status_only = "--status" in args
    changed = 0
    for top in tops:
        if status_only:
            cfg = top / ".cargo" / "config.toml"
            state = "ok" if cfg.exists() else "missing"
        else:
            state = ensure(top, root)
        if state == "written":
            changed += 1
        print(f"{state:>20}  {top}")
    if status_only:
        return 0
    print(f"wt_target: {changed} written, {len(tops)} scanned (root={root})")
    return 0


def self_test() -> int:
    """四条断言：生成 / 幂等 / 无 Cargo.toml 跳过 / 已存在不覆盖。"""
    import tempfile

    failures: list[str] = []

    def expect(name: str, actual, expected) -> None:
        if actual != expected:
            failures.append(name)
            print(f"FAIL {name}：期望 {expected!r}，实际 {actual!r}")

    with tempfile.TemporaryDirectory() as tmp:
        base = pathlib.Path(tmp)
        fake_root = base / "cargo-target"
        fake_root.mkdir()
        wt = base / "wt-a"
        (wt / ".cargo").mkdir(parents=True)
        (wt / "Cargo.toml").write_text("[workspace]\n", encoding="utf-8")

        expect("首次生成", ensure(wt, fake_root), "written")
        expect("内容含 target-dir", "target-dir" in (wt / ".cargo" / "config.toml").read_text(encoding="utf-8"), True)
        expect("再次是 exists（幂等）", ensure(wt, fake_root), "exists")
        # 已存在的文件内容不被改写（手工管理的不动）。
        (wt / ".cargo" / "config.toml").write_text("# manual\n", encoding="utf-8")
        expect("手工文件不被覆盖", ensure(wt, fake_root), "exists")
        expect("手工内容原样", (wt / ".cargo" / "config.toml").read_text(encoding="utf-8"), "# manual\n")

        plain = base / "wt-b"
        plain.mkdir()
        expect("无 Cargo.toml 跳过", ensure(plain, fake_root), "skip:no-cargo-toml")
        expect("无 Cargo.toml 不落盘", (plain / ".cargo").exists(), False)

        missing = base / "nowhere"
        expect("策略根不存在跳过", ensure(wt, missing), "skip:no-target-root")

    if failures:
        return 1
    print("self-test: 7/7 passed")
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(run(sys.argv[1:]))

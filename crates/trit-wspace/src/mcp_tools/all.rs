//! MCP 工具清单（从 `mcp` 拆出，避免单文件超长）。

use serde_json::{Value, json};

fn tool(name: &str, description: &str, props: Value, required: &[&str]) -> Value {
    json!({
        "name": name,
        "description": description,
        "inputSchema": {"type": "object", "properties": props, "required": required},
    })
}


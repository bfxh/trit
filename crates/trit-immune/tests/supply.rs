//! 供应链完整性测试：锁定、比对、三值裁决、挂门禁端到端。
//!
//! 威胁场景对应：
//! 1. **半夜加依赖**：锁文件出现基线没有的包 → `-1`，门禁冻结；
//! 2. **投毒换包**：同 (name, version) checksum 变化 → `-1`（Dispositive）；
//! 3. **正常清理**：依赖移除 → `+1`；
//! 4. **基线可提交**：TSV 编解码往返一致，diff 可读；
//! 5. **清单指纹**：Cargo.toml 被改一行即可检测；
//! 6. **挂门禁端到端**：`-1` finding 经 `Delta::Record` 入账后 merge_gate 收紧。

use trit_immune::*;

fn pin(name: &str, ver: &str, sum: Option<&str>) -> Pin {
    Pin {
        name: name.into(),
        version: ver.into(),
        checksum: sum.map(|s| s.into()),
    }
}

// ── 场景 1：半夜加依赖 → Added → -1 ─────────────────────────────────────

#[test]
fn supply_added_dependency_is_vulnerable() {
    let base = vec![pin("serde", "1.0.200", Some("aa11")), pin("libc", "0.2.150", Some("bb22"))];
    // 半夜多出一个包
    let now = vec![
        pin("serde", "1.0.200", Some("aa11")),
        pin("libc", "0.2.150", Some("bb22")),
        pin("rip_rip_hopefully_not", "9.9.9", Some("deadbeef")),
    ];
    let f = supply::audit(&now, &base);
    assert_eq!(f.len(), 1);
    assert_eq!(f[0].kind, SupplyKind::Added);
    assert_eq!(f[0].verdict, Trit::Vulnerable);
    assert_eq!(f[0].name, "rip_rip_hopefully_not");
}

// ── 场景 2：投毒换包（checksum 变化）→ -1 ───────────────────────────────

#[test]
fn supply_checksum_change_is_dispositive_negative() {
    let base = vec![pin("left-pad", "1.0.0", Some("good0001"))];
    let now = vec![pin("left-pad", "1.0.0", Some("evil6666"))];
    let f = supply::audit(&now, &base);
    assert_eq!(f.len(), 1);
    assert_eq!(f[0].kind, SupplyKind::ChecksumChanged);
    assert_eq!(f[0].verdict, Trit::Vulnerable, "checksum 变化 = 投毒信号");
}

// ── 场景 3：依赖移除 → +1 ────────────────────────────────────────────────

#[test]
fn supply_removed_dependency_is_hardened() {
    let base = vec![pin("legacy-cruft", "0.0.1", Some("cc33"))];
    let now: Vec<Pin> = vec![];
    let f = supply::audit(&now, &base);
    assert_eq!(f.len(), 1);
    assert_eq!(f[0].kind, SupplyKind::Removed);
    assert_eq!(f[0].verdict, Trit::Hardened);
}

// ── 场景 4：同名多版本并存（Cargo.lock 合法形态） ────────────────────────

#[test]
fn supply_multi_version_same_name() {
    let base = vec![pin("w", "1.0.0", Some("s1"))];
    let now = vec![pin("w", "1.0.0", Some("s1")), pin("w", "2.0.0", Some("s2"))];
    let f = supply::audit(&now, &base);
    // 只报新增的 2.0.0；1.0.0 无差异
    assert_eq!(f.len(), 1);
    assert_eq!(f[0].version, "2.0.0");
    assert_eq!(f[0].kind, SupplyKind::Added);

    // 反向：升级后旧版从锁文件消失 → Removed
    let f2 = supply::audit(&base, &now);
    assert_eq!(f2.len(), 1);
    assert_eq!(f2[0].kind, SupplyKind::Removed);
}

// ── 场景 5：基线 TSV 往返 + 指纹 ─────────────────────────────────────────

#[test]
fn supply_baseline_roundtrip_and_fingerprint() {
    let pins = vec![
        pin("serde", "1.0.200", Some("aa11")),
        pin("path-dep", "0.1.0", None),
        pin("z", "3.2.1", Some("ff")),
    ];
    let enc = supply::encode_baseline(&pins);
    let dec = supply::parse_baseline(&enc);
    assert_eq!(dec, pins, "TSV 往返应无损（含 None checksum）");

    // 清单指纹：改一个字节即可检测
    let toml_before = b"[dependencies]\nserde = \"1.0.200\"\n";
    let toml_after = b"[dependencies]\nserde = \"1.0.999\"\n";
    assert_eq!(supply::fingerprint(toml_before), supply::fingerprint(toml_before));
    assert_ne!(supply::fingerprint(toml_before), supply::fingerprint(toml_after));
}

// ── 场景 6：解析真实形态 Cargo.lock（多行 dependencies 数组、其它段） ────

#[test]
fn supply_parse_lock_realistic() {
    let text = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "my-app"
version = "0.1.0"
dependencies = [
 "serde",
 "libc 0.2.150",
]

[[package]]
name = "libc"
version = "0.2.150"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc123"

[[patch.unused]]
name = "should-not-count"
version = "0.0.0"

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "def456"
"#;
    let pins = supply::parse_lock(text);
    let names: Vec<&str> = pins.iter().map(|p| p.name.as_str()).collect();
    assert_eq!(names, vec!["my-app", "libc", "serde"], "[[patch.unused]] 不计入");
    assert_eq!(pins[0].checksum, None, "workspace 成员无 checksum");
    assert_eq!(pins[1].checksum.as_deref(), Some("abc123"));
}

// ── 场景 7：端到端——finding 挂 DAG，门禁收紧 ───────────────────────────

#[test]
fn supply_findings_drive_merge_gate_block() {
    let mut dag = ImmuneDag::root("app");
    let dep = dag.spawn(NodeId(0), NodeKind::Delta, "依赖面:serde");

    // 初审 +1（此前审计过）
    dag.record(dep, Trit::Hardened, None, "基线内依赖");
    let tip = dag.spawn(dep, NodeKind::Delta, "release-1.2");
    dag.record(tip, Trit::Hardened, None, "通过");

    // 供应链审计发现 checksum 变化 → -1 入账（与扫描器同一条 Delta 路径）
    let base = vec![pin("serde", "1.0.200", Some("aa11"))];
    let now = vec![pin("serde", "1.0.200", Some("EVIL"))];
    for f in supply::audit(&now, &base) {
        if f.verdict == Trit::Vulnerable {
            dag.record(tip, Trit::Vulnerable, None, &format!("supply:{}:{}", f.name, f.kind as u8 as char));
        }
    }

    // 门禁必须冻结/阻断——不允许带毒放行
    let gate = dag.merge_gate(tip);
    assert_ne!(
        gate,
        GateDecision::Allow,
        "供应链 -1 后不得放行，实际 {gate:?}"
    );

    // 恢复：checksum 回到基线值（重新审计无差异）→ 人工复核后复原
    let clean = supply::audit(&base, &base);
    assert!(clean.is_empty());
    dag.record(tip, Trit::Hardened, None, "人工复核：checksum 回归基线");
    dag.record(dep, Trit::Hardened, None, "人工复核通过");
    assert_eq!(dag.merge_gate(tip), GateDecision::Allow);
}

// ── 场景 8：intake 管线端到端（Journal 落盘 + 门禁） ─────────────────────

#[cfg(feature = "full")]
#[test]
fn supply_intake_pipeline_records_findings_and_blocks_gate() {
    let p = std::env::temp_dir().join(format!(
        "trit-supply-intake-{}.journal",
        std::process::id()
    ));
    let _ = std::fs::remove_file(&p);

    let mut j = Journal::create_as(&p, "supply-intake", 0).unwrap();
    let root = NodeId(0);
    let rel = j.spawn(root, NodeKind::Delta, "release-1.0").unwrap();
    j.record(rel, Trit::Hardened, None, "基线审计通过").unwrap();

    // 基线：serde 已锁定；当前锁文件：serde 被换 checksum + 多出未知包
    let baseline = vec![Pin { name: "serde".into(), version: "1.0.200".into(), checksum: Some("good".into()) }];
    let lock_now = vec![
        Pin { name: "serde".into(), version: "1.0.200".into(), checksum: Some("EVIL".into()) },
        Pin { name: "mystery".into(), version: "0.0.1".into(), checksum: None },
    ];

    let n = intake::intake_supply(&mut j, rel, "nightly-audit", &lock_now, &baseline).unwrap();
    assert_eq!(n, 2, "两条 finding 都应立账");
    let _ = j.into_dag().unwrap();

    // 重开验证持久化
    let j2 = Journal::open_as(&p, 0).unwrap();
    let dag = j2.dag();
    let flags: Vec<&dag::Node> = dag
        .nodes()
        .iter()
        .filter(|nd| nd.title.starts_with("供应链:"))
        .collect();
    assert_eq!(flags.len(), 2);
    assert!(flags.iter().all(|nd| nd.verdict == Trit::Vulnerable));

    // 门禁：release 节点的因果链含两条 -1 → 不得放行
    let gate = dag.merge_gate(rel);
    assert_ne!(gate, GateDecision::Allow, "供应链投毒后不得放行，实际 {gate:?}");
    drop(j2);
    let _ = std::fs::remove_file(&p);
}

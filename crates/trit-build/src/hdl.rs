//! HDL 真仿真（M2 缺口补齐）：生成自检 testbench，交给 iverilog/vvp 跑。
//!
//! 为什么不在 Rust 里再写一个解释器：M2 的 `design.v` 只被测试内位级解释器验过，
//! 那证明的是"我生成的式子符合我的理解"。这里把同一份 `design.v` 交给独立 HDL 工具，
//! 逐行比对 `expected.mem`（2 bit/行：`{y_p,y_n}`）——工具链不同，错误才有机会暴露。
//!
//! 测试平台用数组存输入轨，循环遍历 0..3^n；不展开 3^n 行，12 变量也能生成。

use std::env;
use std::fs;
use std::path::Path;
use std::process::Command;

use anyhow::{Context, Result, bail};
use trit_core::value::Ternary;

/// `{y_p, y_n}` 的 2 bit 编码：2=真、1=假、0=未知。
fn rail_code(value: Ternary) -> u8 {
    match value {
        Ternary::True => 2,
        Ternary::False => 1,
        Ternary::Unknown => 0,
    }
}

pub fn expected_mem(values: &[Ternary]) -> String {
    let mut text = String::with_capacity(values.len() * 2);
    for value in values {
        text.push(char::from_digit(u32::from(rail_code(*value)), 16).expect("0..=2"));
        text.push('\n');
    }
    text
}

/// 生成自检 testbench（模块名固定 `trit_module`）。
pub fn testbench(vars: &[String], values: &[Ternary]) -> String {
    let rows = values.len();
    let nvars = vars.len();
    let mut text = String::new();
    text.push_str("// generated by trit-build --verify-hdl\n");
    text.push_str("`timescale 1ns/1ps\n\n");
    text.push_str("module trit_tb;\n");
    if nvars > 0 {
        text.push_str(&format!("  reg in_p [0:{}];\n", nvars - 1));
        text.push_str(&format!("  reg in_n [0:{}];\n", nvars - 1));
    }
    text.push_str("  wire y_p, y_n;\n");
    text.push_str(&format!("  reg [1:0] expected [0:{}];\n", rows - 1));
    text.push_str("  integer code, rest, digit, index, errors;\n\n");
    text.push_str("  trit_module dut(\n");
    for (index, var) in vars.iter().enumerate() {
        text.push_str(&format!(
            "    .{var}_p(in_p[{index}]), .{var}_n(in_n[{index}]),\n"
        ));
    }
    text.push_str("    .y_p(y_p), .y_n(y_n)\n  );\n\n");
    text.push_str("  initial begin\n");
    text.push_str("    errors = 0;\n");
    text.push_str("    $readmemh(\"expected.mem\", expected);\n");
    text.push_str(&format!(
        "    for (code = 0; code < {rows}; code = code + 1) begin\n"
    ));
    text.push_str("      rest = code;\n");
    if nvars > 0 {
        text.push_str(&format!(
            "      for (index = 0; index < {nvars}; index = index + 1) begin\n"
        ));
        text.push_str("        digit = rest % 3;\n");
        text.push_str("        rest = rest / 3;\n");
        text.push_str("        in_p[index] = (digit == 2);\n");
        text.push_str("        in_n[index] = (digit == 0);\n");
        text.push_str("      end\n");
    }
    text.push_str("      #1;\n");
    text.push_str("      if ({y_p, y_n} !== expected[code]) begin\n");
    text.push_str("        $display(\"MISMATCH code=%0d rails=%b expected=%b\", code, {y_p, y_n}, expected[code]);\n");
    text.push_str("        errors = errors + 1;\n");
    text.push_str("        if (errors > 8) $fatal(1, \"too many mismatches\");\n");
    text.push_str("      end\n");
    text.push_str("    end\n");
    text.push_str("    if (errors != 0) $fatal(1, \"trit-build hdl: %0d mismatches\", errors);\n");
    text.push_str(&format!("    $display(\"OK {rows} rows\");\n"));
    text.push_str("    $finish;\n");
    text.push_str("  end\nendmodule\n");
    text
}

/// 跑 iverilog + vvp；返回 vvp 的最后一行（`OK N rows`）。
pub fn verify(out_dir: &Path) -> Result<String> {
    let iverilog = env::var("TRIT_IVERILOG").unwrap_or_else(|_| "iverilog".to_string());
    let vvp = env::var("TRIT_VVP").unwrap_or_else(|_| "vvp".to_string());
    let compile = Command::new(&iverilog)
        .args(["-g2012", "-o", "design.vvp", "design_tb.v", "design.v"])
        .current_dir(out_dir)
        .output()
        .with_context(|| {
            format!("找不到 HDL 仿真器 {iverilog:?}（安装 icarus-verilog，或设置 TRIT_IVERILOG）")
        })?;
    if !compile.status.success() {
        bail!(
            "iverilog 编译 design.v/design_tb.v 失败：\n{}",
            String::from_utf8_lossy(&compile.stderr)
        );
    }
    let run = Command::new(&vvp)
        .arg("design.vvp")
        .current_dir(out_dir)
        .output()
        .context("找不到 vvp（与 iverilog 同目录；可用 TRIT_VVP 指定）")?;
    let stdout = String::from_utf8_lossy(&run.stdout);
    if !run.status.success() {
        bail!(
            "HDL 仿真失败（退出 {}）：\n{}\n{}",
            run.status.code().unwrap_or(-1),
            stdout,
            String::from_utf8_lossy(&run.stderr)
        );
    }
    let ok_line = stdout
        .lines()
        .map(str::trim)
        .find(|line| line.starts_with("OK "))
        .map(str::to_string);
    let Some(ok_line) = ok_line else {
        bail!("HDL 仿真没有给出 OK（输出：{stdout}）");
    };
    fs::remove_file(out_dir.join("design.vvp")).ok();
    Ok(ok_line)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn expected_mem_encodes_rails() {
        assert_eq!(
            expected_mem(&[Ternary::True, Ternary::False, Ternary::Unknown]),
            "2
1
0
"
        );
    }
}

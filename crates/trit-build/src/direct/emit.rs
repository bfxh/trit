//! `direct.c` 的渲染：表由 `Algebra` 现算，节点按后序发语句。
//!
//! 单用节点在 `inline` 里决定是否并进父表达式（沿单用边展开，扇出即停），根节点由
//! `return` 直接展开。二元调用一律展开成 `T[...][3*l+r+4]` 表索引：紧凑索引每次调用
//! 都比 `trit_bin` helper 调用短，helper 的固定声明无法摊销。

use trit_core::Algebra;

use super::ir::Op;
use format::{alg_name, push_table};

mod body;
mod format;
mod inline;
mod tables;

/// 表达式 → `direct.c` 全文。
pub(super) fn render(ops: Vec<Op>, vars: &[String], alg: Algebra) -> String {
    let binary_tables = tables::used(&ops, alg);
    let inlined = inline::targets(&ops);
    let mut prefix = String::new();
    prefix.push_str("/* generated by trit-build; backend = direct-c; 语义 = ");
    prefix.push_str(alg_name(alg));
    prefix.push_str("; 变量顺序 = ");
    prefix.push_str(&vars.join(","));
    prefix.push_str(" */\n");
    prefix.push_str("/* 直算：节点顺序发语句，单用节点并句；不展开 3^n 表。 */\n");
    prefix.push_str("#include <stdint.h>\n\n");
    let (tables, merged) = inline::tables(&binary_tables);
    match merged {
        Some(values) => push_table(&mut prefix, "T", &values),
        None => {
            if let Some((name, values)) = binary_tables.first() {
                push_table(&mut prefix, name, values);
            }
        }
    }

    let mut text = prefix;
    if !binary_tables.is_empty() {
        text.push('\n');
    }
    text.push_str(&body::body(&ops, vars, &inlined, &tables));
    text
}


//! `direct.c` 的渲染：表由 `Algebra` 现算，节点按后序发语句。
//!
//! 单用节点在 `inline` 里决定是否并进父表达式（沿单用边展开，扇出即停），根节点由
//! `return` 直接展开。二元调用先各写一版：共用 `trit_bin` helper，或全部展开成
//! 表索引；两版只差这一处，最终按整篇字节数选短者，不再依赖固定调用阈值。

use trit_core::Algebra;

use super::ir::Op;
use super::{binary_table, gate_table};
use format::{alg_name, push_table};
use trit_circuit::GateKind;

mod body;
mod format;
mod inline;

const BIN_HELPER: &str = concat!(
    "static inline int8_t trit_bin(const int8_t t[9], int8_t a, int8_t b) {\n",
    "    return t[(a + 1) * 3 + (b + 1)];\n",
    "}\n"
);

/// 表达式 → `direct.c` 全文。
pub(super) fn render(ops: Vec<Op>, vars: &[String], alg: Algebra) -> String {
    let mut uses_and = false;
    let mut uses_or = false;
    let mut uses_xor = false;
    let mut uses_xor2 = false;
    let mut uses_implies = false;
    let mut uses_equiv = false;
    for op in &ops {
        match op {
            Op::And(_, _) => uses_and = true,
            Op::Or(_, _) => uses_or = true,
            Op::Xor(_, _) => uses_xor = true,
            Op::Xor2(_, _) => uses_xor2 = true,
            Op::Implies(_, _) => uses_implies = true,
            Op::Equiv(_, _) => uses_equiv = true,
            Op::Not(_) | Op::Const(_) | Op::Var(_) => {}
        }
    }
    let inlined = inline::targets(&ops);

    let mut prefix = String::new();
    prefix.push_str("/* generated by trit-build; backend = direct-c; 语义 = ");
    prefix.push_str(alg_name(alg));
    prefix.push_str("; 变量顺序 = ");
    prefix.push_str(&vars.join(","));
    prefix.push_str(" */\n");
    prefix.push_str("/* 直算：节点顺序发语句，单用节点并句；不展开 3^n 表。 */\n");
    prefix.push_str("#include <stdint.h>\n\n");

    let mut binary_tables = Vec::new();
    if uses_and {
        binary_tables.push(("T_AND", binary_table(alg, Algebra::and)));
    }
    if uses_or {
        binary_tables.push(("T_OR", binary_table(alg, Algebra::or)));
    }
    if uses_xor {
        binary_tables.push(("T_XOR", binary_table(alg, Algebra::strong_add)));
    }
    if uses_xor2 {
        binary_tables.push(("T_XOR2", gate_table(alg, GateKind::XorClassic)));
    }
    if uses_implies {
        binary_tables.push(("T_IMPL", binary_table(alg, Algebra::implies)));
    }
    if uses_equiv {
        binary_tables.push(("T_EQUIV", binary_table(alg, Algebra::equiv)));
    }
    for (name, table) in &binary_tables {
        push_table(&mut prefix, name, table);
    }

    let mut with_helper = prefix.clone();
    if !binary_tables.is_empty() {
        with_helper.push_str(BIN_HELPER);
        with_helper.push('\n');
    }
    with_helper.push_str(&body::body(&ops, vars, &inlined, false));

    let mut without_helper = prefix;
    if !binary_tables.is_empty() {
        without_helper.push('\n');
    }
    without_helper.push_str(&body::body(&ops, vars, &inlined, true));

    if without_helper.len() <= with_helper.len() {
        without_helper
    } else {
        with_helper
    }
}


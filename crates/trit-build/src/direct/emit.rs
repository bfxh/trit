//! `direct.c` 的渲染：表由 `Algebra` 现算，节点按后序各发一条语句。

//! 单用取反子式内联：`Not(x)` 的 `x` 只被这一处引用时，子式不再单独落临时变量，
//! 直接并成 `trit_not(trit_bin(T_AND, t0, t1))` 一条语句（两个节点 → 一条 C 语句）。
//! 被多处引用的子式仍单独成变量，网表扇出不会被复制。

use trit_core::Algebra;

use super::ir::Op;
use super::{binary_table, code, gate_table, unary_table};
use trit_circuit::GateKind;

/// 表达式 → `direct.c` 全文。
pub(super) fn render(ops: Vec<Op>, vars: &[String], alg: Algebra) -> String {
    let mut uses_not = false;
    let mut uses_and = false;
    let mut uses_or = false;
    let mut uses_xor = false;
    let mut uses_xor2 = false;
    let mut uses_implies = false;
    let mut uses_equiv = false;
    for op in &ops {
        match op {
            Op::Not(_) => uses_not = true,
            Op::And(_, _) => uses_and = true,
            Op::Or(_, _) => uses_or = true,
            Op::Xor(_, _) => uses_xor = true,
            Op::Xor2(_, _) => uses_xor2 = true,
            Op::Implies(_, _) => uses_implies = true,
            Op::Equiv(_, _) => uses_equiv = true,
            Op::Const(_) | Op::Var(_) => {}
        }
    }
    let inlined = inline_targets(&ops);

    let mut text = String::new();
    text.push_str("/* generated by trit-build; backend = direct-c; 语义 = ");
    text.push_str(alg_name(alg));
    text.push_str("; 变量顺序 = ");
    text.push_str(&vars.join(","));
    text.push_str(" */\n");
    text.push_str("/* 直算：节点顺序发语句，单用取反并句；不展开 3^n 表。 */\n");
    text.push_str("#include <stdint.h>\n\n");

    if uses_not {
        push_table(&mut text, "T_NOT", &unary_table(alg, Algebra::not));
        text.push_str("static inline int8_t trit_not(int8_t a) { return T_NOT[a + 1]; }\n");
    }
    let mut binary_tables = Vec::new();
    if uses_and {
        binary_tables.push(("T_AND", binary_table(alg, Algebra::and)));
    }
    if uses_or {
        binary_tables.push(("T_OR", binary_table(alg, Algebra::or)));
    }
    if uses_xor {
        binary_tables.push(("T_XOR", binary_table(alg, Algebra::strong_add)));
    }
    if uses_xor2 {
        binary_tables.push(("T_XOR2", gate_table(alg, GateKind::XorClassic)));
    }
    if uses_implies {
        binary_tables.push(("T_IMPL", binary_table(alg, Algebra::implies)));
    }
    if uses_equiv {
        binary_tables.push(("T_EQUIV", binary_table(alg, Algebra::equiv)));
    }
    for (name, table) in &binary_tables {
        push_table(&mut text, name, table);
    }
    if !binary_tables.is_empty() {
        text.push_str(
            "static inline int8_t trit_bin(const int8_t t[9], int8_t a, int8_t b) {\n\
             \x20   return t[(a + 1) * 3 + (b + 1)];\n\
             }\n",
        );
    }
    text.push('\n');

    text.push_str("int8_t trit_direct(const int8_t *vars, unsigned nvars) {\n");
    if !vars.is_empty() {
        text.push_str("    if (nvars < ");
        text.push_str(&vars.len().to_string());
        text.push_str("u) return 0; /* 入参不足：按 X 处理，fail-closed */\n");
    } else {
        text.push_str("    (void)nvars;\n");
    }
    let mut names: Vec<Option<usize>> = vec![None; ops.len()];
    let mut next = 0usize;
    for (index, op) in ops.iter().enumerate() {
        if inlined[index] {
            continue;
        }
        names[index] = Some(next);
        let line = match op {
            Op::Const(value) => format!("    int8_t t{next} = {};\n", code(*value)),
            Op::Var(slot) => format!("    int8_t t{next} = vars[{slot}];\n"),
            Op::Not(inner) if inlined[*inner] => {
                format!(
                    "    int8_t t{next} = trit_not({});\n",
                    expr(&ops, &names, *inner)
                )
            }
            Op::Not(inner) => {
                format!(
                    "    int8_t t{next} = trit_not(t{});\n",
                    name(&names, *inner)
                )
            }
            Op::And(left, right) => {
                let (left, right) = (name(&names, *left), name(&names, *right));
                format!("    int8_t t{next} = trit_bin(T_AND, t{left}, t{right});\n")
            }
            Op::Or(left, right) => {
                let (left, right) = (name(&names, *left), name(&names, *right));
                format!("    int8_t t{next} = trit_bin(T_OR, t{left}, t{right});\n")
            }
            Op::Xor(left, right) => {
                let (left, right) = (name(&names, *left), name(&names, *right));
                format!("    int8_t t{next} = trit_bin(T_XOR, t{left}, t{right});\n")
            }
            Op::Xor2(left, right) => {
                let (left, right) = (name(&names, *left), name(&names, *right));
                format!("    int8_t t{next} = trit_bin(T_XOR2, t{left}, t{right});\n")
            }
            Op::Implies(left, right) => {
                let (left, right) = (name(&names, *left), name(&names, *right));
                format!("    int8_t t{next} = trit_bin(T_IMPL, t{left}, t{right});\n")
            }
            Op::Equiv(left, right) => {
                let (left, right) = (name(&names, *left), name(&names, *right));
                format!("    int8_t t{next} = trit_bin(T_EQUIV, t{left}, t{right});\n")
            }
        };
        text.push_str(&line);
        next += 1;
    }
    text.push_str("    return t");
    text.push_str(&names[ops.len() - 1].expect("根节点一定发语句").to_string());
    text.push_str(";\n}\n");
    text
}

fn name(names: &[Option<usize>], index: usize) -> usize {
    names[index].expect("操作数先于父节点发射，且不会被内联")
}

/// 子式只被一个 `Not` 引用时，标记它不单独发语句；`Not(Not(x))` 已由折叠消掉。
fn inline_targets(ops: &[Op]) -> Vec<bool> {
    let mut uses = vec![0usize; ops.len()];
    for op in ops {
        match *op {
            Op::Not(inner) => uses[inner] += 1,
            Op::And(left, right)
            | Op::Or(left, right)
            | Op::Xor(left, right)
            | Op::Xor2(left, right)
            | Op::Implies(left, right)
            | Op::Equiv(left, right) => {
                uses[left] += 1;
                uses[right] += 1;
            }
            Op::Const(_) | Op::Var(_) => {}
        }
    }
    let mut inlined = vec![false; ops.len()];
    for op in ops {
        let Op::Not(inner) = *op else { continue };
        if uses[inner] == 1 && is_binary(&ops[inner]) {
            inlined[inner] = true;
        }
    }
    inlined
}

fn is_binary(op: &Op) -> bool {
    matches!(
        op,
        Op::And(..) | Op::Or(..) | Op::Xor(..) | Op::Xor2(..) | Op::Implies(..) | Op::Equiv(..)
    )
}

/// 内联子式的 C 表达式；它的操作数一定已单独发过语句（否则会被更外层引用两次）。
fn expr(ops: &[Op], names: &[Option<usize>], index: usize) -> String {
    let atom = |operand: usize| name(names, operand);
    match ops[index] {
        Op::Const(value) => code(value).to_string(),
        Op::Var(slot) => format!("vars[{slot}]"),
        Op::And(left, right) => format!("trit_bin(T_AND, t{}, t{})", atom(left), atom(right)),
        Op::Or(left, right) => format!("trit_bin(T_OR, t{}, t{})", atom(left), atom(right)),
        Op::Xor(left, right) => format!("trit_bin(T_XOR, t{}, t{})", atom(left), atom(right)),
        Op::Xor2(left, right) => format!("trit_bin(T_XOR2, t{}, t{})", atom(left), atom(right)),
        Op::Implies(left, right) => format!("trit_bin(T_IMPL, t{}, t{})", atom(left), atom(right)),
        Op::Equiv(left, right) => format!("trit_bin(T_EQUIV, t{}, t{})", atom(left), atom(right)),
        Op::Not(inner) => format!("trit_not(t{})", atom(inner)),
    }
}

fn push_table(text: &mut String, name: &str, table: &[i8]) {
    text.push_str("static const int8_t ");
    text.push_str(name);
    text.push('[');
    text.push_str(&table.len().to_string());
    text.push_str("] = {");
    for value in table {
        text.push(' ');
        text.push_str(&value.to_string());
        text.push(',');
    }
    text.push_str(" };\n");
}

fn alg_name(alg: Algebra) -> &'static str {
    match alg {
        Algebra::Kleene => "kleene",
        Algebra::Lukasiewicz => "lukasiewicz",
        Algebra::Bochvar => "bochvar",
    }
}


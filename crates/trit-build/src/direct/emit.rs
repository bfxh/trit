//! `direct.c` 的渲染：表由 `Algebra` 现算，节点按后序发语句。
//!
//! 取反子式的内联决策与表达式展开在 `inline`：`Not(x)` 的 `x` 只被这一处引用时，
//! `x` 不再单独落临时变量，沿单用操作数递归并进父语句；扇出节点仍单独成变量，
//! 网表扇出不复制。内联后临时变量重编号为连续 `t0..tn`。

use trit_core::Algebra;

use super::ir::Op;
use super::{binary_table, code, gate_table, unary_table};
use trit_circuit::GateKind;

mod inline;

/// 表达式 → `direct.c` 全文。
pub(super) fn render(ops: Vec<Op>, vars: &[String], alg: Algebra) -> String {
    let mut uses_not = false;
    let mut uses_and = false;
    let mut uses_or = false;
    let mut uses_xor = false;
    let mut uses_xor2 = false;
    let mut uses_implies = false;
    let mut uses_equiv = false;
    for op in &ops {
        match op {
            Op::Not(_) => uses_not = true,
            Op::And(_, _) => uses_and = true,
            Op::Or(_, _) => uses_or = true,
            Op::Xor(_, _) => uses_xor = true,
            Op::Xor2(_, _) => uses_xor2 = true,
            Op::Implies(_, _) => uses_implies = true,
            Op::Equiv(_, _) => uses_equiv = true,
            Op::Const(_) | Op::Var(_) => {}
        }
    }
    let inlined = inline::targets(&ops);

    let mut text = String::new();
    text.push_str("/* generated by trit-build; backend = direct-c; 语义 = ");
    text.push_str(alg_name(alg));
    text.push_str("; 变量顺序 = ");
    text.push_str(&vars.join(","));
    text.push_str(" */\n");
    text.push_str("/* 直算：节点顺序发语句，单用取反并句；不展开 3^n 表。 */\n");
    text.push_str("#include <stdint.h>\n\n");

    if uses_not {
        push_table(&mut text, "T_NOT", &unary_table(alg, Algebra::not));
        text.push_str("static inline int8_t trit_not(int8_t a) { return T_NOT[a + 1]; }\n");
    }
    let mut binary_tables = Vec::new();
    if uses_and {
        binary_tables.push(("T_AND", binary_table(alg, Algebra::and)));
    }
    if uses_or {
        binary_tables.push(("T_OR", binary_table(alg, Algebra::or)));
    }
    if uses_xor {
        binary_tables.push(("T_XOR", binary_table(alg, Algebra::strong_add)));
    }
    if uses_xor2 {
        binary_tables.push(("T_XOR2", gate_table(alg, GateKind::XorClassic)));
    }
    if uses_implies {
        binary_tables.push(("T_IMPL", binary_table(alg, Algebra::implies)));
    }
    if uses_equiv {
        binary_tables.push(("T_EQUIV", binary_table(alg, Algebra::equiv)));
    }
    for (name, table) in &binary_tables {
        push_table(&mut text, name, table);
    }
    if !binary_tables.is_empty() {
        text.push_str(
            "static inline int8_t trit_bin(const int8_t t[9], int8_t a, int8_t b) {\n\
             \x20   return t[(a + 1) * 3 + (b + 1)];\n\
             }\n",
        );
    }
    text.push('\n');

    text.push_str("int8_t trit_direct(const int8_t *vars, unsigned nvars) {\n");
    if !vars.is_empty() {
        text.push_str("    if (nvars < ");
        text.push_str(&vars.len().to_string());
        text.push_str("u) return 0; /* 入参不足：按 X 处理，fail-closed */\n");
    } else {
        text.push_str("    (void)nvars;\n");
    }
    let mut names: Vec<Option<usize>> = vec![None; ops.len()];
    let mut next = 0usize;
    for (index, op) in ops.iter().enumerate() {
        if inlined[index] {
            continue;
        }
        names[index] = Some(next);
        let line = match op {
            Op::Const(value) => format!("    int8_t t{next} = {};\n", code(*value)),
            Op::Var(slot) => format!("    int8_t t{next} = vars[{slot}];\n"),
            Op::Not(inner) => format!(
                "    int8_t t{next} = trit_not({});\n",
                inline::expr(&ops, &names, &inlined, *inner)
            ),
            Op::And(left, right) => format!(
                "    int8_t t{next} = trit_bin(T_AND, {}, {});\n",
                inline::expr(&ops, &names, &inlined, *left),
                inline::expr(&ops, &names, &inlined, *right)
            ),
            Op::Or(left, right) => format!(
                "    int8_t t{next} = trit_bin(T_OR, {}, {});\n",
                inline::expr(&ops, &names, &inlined, *left),
                inline::expr(&ops, &names, &inlined, *right)
            ),
            Op::Xor(left, right) => format!(
                "    int8_t t{next} = trit_bin(T_XOR, {}, {});\n",
                inline::expr(&ops, &names, &inlined, *left),
                inline::expr(&ops, &names, &inlined, *right)
            ),
            Op::Xor2(left, right) => format!(
                "    int8_t t{next} = trit_bin(T_XOR2, {}, {});\n",
                inline::expr(&ops, &names, &inlined, *left),
                inline::expr(&ops, &names, &inlined, *right)
            ),
            Op::Implies(left, right) => format!(
                "    int8_t t{next} = trit_bin(T_IMPL, {}, {});\n",
                inline::expr(&ops, &names, &inlined, *left),
                inline::expr(&ops, &names, &inlined, *right)
            ),
            Op::Equiv(left, right) => format!(
                "    int8_t t{next} = trit_bin(T_EQUIV, {}, {});\n",
                inline::expr(&ops, &names, &inlined, *left),
                inline::expr(&ops, &names, &inlined, *right)
            ),
        };
        text.push_str(&line);
        next += 1;
    }
    text.push_str("    return t");
    text.push_str(&names[ops.len() - 1].expect("根节点一定发语句").to_string());
    text.push_str(";\n}\n");
    text
}

fn push_table(text: &mut String, name: &str, table: &[i8]) {
    text.push_str("static const int8_t ");
    text.push_str(name);
    text.push('[');
    text.push_str(&table.len().to_string());
    text.push_str("] = {");
    for value in table {
        text.push(' ');
        text.push_str(&value.to_string());
        text.push(',');
    }
    text.push_str(" };\n");
}

fn alg_name(alg: Algebra) -> &'static str {
    match alg {
        Algebra::Kleene => "kleene",
        Algebra::Lukasiewicz => "lukasiewicz",
        Algebra::Bochvar => "bochvar",
    }
}


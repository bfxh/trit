//! TTIR → C 直算后端（`--backend direct|both` 产出 `direct.c`）。
//!
//! 和 `lookup.c` 是同一条边界上的两种产物：
//! - `lookup.c` 把 3^n 真值表整块塞进 C，运行时一次索引；
//! - `direct.c` 把表达式或 Verilog 组合网表**降成线性 IR**（每个节点一条 `int8_t tN = ...;`），
//!   交换律规范化后再做 CSE，出口过一遍死代码消除；运行时按节点顺序算，不展开 3^n 表。
//!
//! 语义不靠手写 C 算子保证：六张 3×3/3 表由 [`Algebra`] 现算，测试再拿
//! `trit_eval::eval` 逐赋值对拍。生成物仍需 C 工具链编译 —— 这与
//! `docs/reference/TERNARY-TOOLCHAIN.md` §7「不做二进制后端」一致。
//!
//! 函数签名与 `lookup.c` 的 `trit_lookup` 平行：
//! `int8_t trit_direct(const int8_t *vars, unsigned nvars)`。
//! 入参不足（`nvars < 变量数`）一律返回 `0`（X），fail-closed，不读越界内存。

use anyhow::Result;
use trit_circuit::{Circuit, GateKind};
use trit_core::{Algebra, Expr, value::Ternary};

/// 三值枚举顺序 = C 侧 `-1/0/1` 的顺序，也是表的下标顺序。
const VALUES: [Ternary; 3] = [Ternary::False, Ternary::Unknown, Ternary::True];

mod fold;
mod ir;
mod lower;
mod netlist;
mod verify;
use ir::Op;
use lower::lower;
pub(crate) use verify::verify;

fn code(value: Ternary) -> i8 {
    match value {
        Ternary::False => -1,
        Ternary::Unknown => 0,
        Ternary::True => 1,
    }
}

fn unary_table(alg: Algebra, function: fn(Algebra, Ternary) -> Ternary) -> [i8; 3] {
    let mut table = [0i8; 3];
    for (index, value) in VALUES.iter().enumerate() {
        table[index] = code(function(alg, *value));
    }
    table
}

fn binary_table(alg: Algebra, function: fn(Algebra, Ternary, Ternary) -> Ternary) -> [i8; 9] {
    let mut table = [0i8; 9];
    for (row, left) in VALUES.iter().enumerate() {
        for (column, right) in VALUES.iter().enumerate() {
            table[row * 3 + column] = code(function(alg, *left, *right));
        }
    }
    table
}

/// 网表门型的 3×3 表：直接用 `trit-circuit` 的 `GateKind::eval`，与仿真同一口径。
fn gate_table(alg: Algebra, kind: GateKind) -> [i8; 9] {
    let mut table = [0i8; 9];
    for (row, left) in VALUES.iter().enumerate() {
        for (column, right) in VALUES.iter().enumerate() {
            table[row * 3 + column] = code(kind.eval(&[*left, *right], alg));
        }
    }
    table
}

/// 表达式 → `direct.c` 全文。
pub(crate) fn emit(expr: &Expr, vars: &[String], alg: Algebra) -> Result<String> {
    let ops = fold::fold(lower(expr, vars)?, alg);
    Ok(render(&ops, vars, alg))
}

/// Verilog 组合网表 → `direct.c` 全文（只降选中输出的扇入锥）。
pub(crate) fn emit_netlist(
    circuit: &Circuit,
    output: &str,
    vars: &[String],
    alg: Algebra,
) -> Result<String> {
    let ops = fold::fold(netlist::lower(circuit, output, vars)?, alg);
    Ok(render(&ops, vars, alg))
}

fn render(ops: &[Op], vars: &[String], alg: Algebra) -> String {
    let mut uses_not = false;
    let mut uses_and = false;
    let mut uses_or = false;
    let mut uses_xor = false;
    let mut uses_xor2 = false;
    let mut uses_implies = false;
    let mut uses_equiv = false;
    for op in ops {
        match op {
            Op::Not(_) => uses_not = true,
            Op::And(_, _) => uses_and = true,
            Op::Or(_, _) => uses_or = true,
            Op::Xor(_, _) => uses_xor = true,
            Op::Xor2(_, _) => uses_xor2 = true,
            Op::Implies(_, _) => uses_implies = true,
            Op::Equiv(_, _) => uses_equiv = true,
            Op::Const(_) | Op::Var(_) => {}
        }
    }

    let mut text = String::new();
    text.push_str("/* generated by trit-build; backend = direct-c; 语义 = ");
    text.push_str(alg_name(alg));
    text.push_str("; 变量顺序 = ");
    text.push_str(&vars.join(","));
    text.push_str(" */\n");
    text.push_str(
        "/* 直算：每个节点一条语句，不展开 3^n 真值表；表由 trit-core 的 Algebra 现算。 */\n",
    );
    text.push_str("#include <stdint.h>\n\n");

    if uses_not {
        push_table(&mut text, "T_NOT", &unary_table(alg, Algebra::not));
        text.push_str("static inline int8_t trit_not(int8_t a) { return T_NOT[a + 1]; }\n");
    }
    let mut binary_tables = Vec::new();
    if uses_and {
        binary_tables.push(("T_AND", binary_table(alg, Algebra::and)));
    }
    if uses_or {
        binary_tables.push(("T_OR", binary_table(alg, Algebra::or)));
    }
    if uses_xor {
        binary_tables.push(("T_XOR", binary_table(alg, Algebra::strong_add)));
    }
    if uses_xor2 {
        binary_tables.push(("T_XOR2", gate_table(alg, GateKind::XorClassic)));
    }
    if uses_implies {
        binary_tables.push(("T_IMPL", binary_table(alg, Algebra::implies)));
    }
    if uses_equiv {
        binary_tables.push(("T_EQUIV", binary_table(alg, Algebra::equiv)));
    }
    for (name, table) in &binary_tables {
        push_table(&mut text, name, table);
    }
    if !binary_tables.is_empty() {
        text.push_str(
            "static inline int8_t trit_bin(const int8_t t[9], int8_t a, int8_t b) {\n\
             \x20   return t[(a + 1) * 3 + (b + 1)];\n\
             }\n",
        );
    }
    text.push('\n');

    text.push_str("int8_t trit_direct(const int8_t *vars, unsigned nvars) {\n");
    if !vars.is_empty() {
        text.push_str("    if (nvars < ");
        text.push_str(&vars.len().to_string());
        text.push_str("u) return 0; /* 入参不足：按 X 处理，fail-closed */\n");
    } else {
        text.push_str("    (void)nvars;\n");
    }
    for (index, op) in ops.iter().enumerate() {
        let line = match op {
            Op::Const(value) => format!("    int8_t t{index} = {};\n", code(*value)),
            Op::Var(slot) => format!("    int8_t t{index} = vars[{slot}];\n"),
            Op::Not(inner) => format!("    int8_t t{index} = trit_not(t{inner});\n"),
            Op::And(left, right) => {
                format!("    int8_t t{index} = trit_bin(T_AND, t{left}, t{right});\n")
            }
            Op::Or(left, right) => {
                format!("    int8_t t{index} = trit_bin(T_OR, t{left}, t{right});\n")
            }
            Op::Xor(left, right) => {
                format!("    int8_t t{index} = trit_bin(T_XOR, t{left}, t{right});\n")
            }
            Op::Xor2(left, right) => {
                format!("    int8_t t{index} = trit_bin(T_XOR2, t{left}, t{right});\n")
            }
            Op::Implies(left, right) => {
                format!("    int8_t t{index} = trit_bin(T_IMPL, t{left}, t{right});\n")
            }
            Op::Equiv(left, right) => {
                format!("    int8_t t{index} = trit_bin(T_EQUIV, t{left}, t{right});\n")
            }
        };
        text.push_str(&line);
    }
    text.push_str("    return t");
    text.push_str(&(ops.len() - 1).to_string());
    text.push_str(";\n}\n");
    text
}

fn push_table(text: &mut String, name: &str, table: &[i8]) {
    text.push_str("static const int8_t ");
    text.push_str(name);
    text.push('[');
    text.push_str(&table.len().to_string());
    text.push_str("] = {");
    for value in table {
        text.push(' ');
        text.push_str(&value.to_string());
        text.push(',');
    }
    text.push_str(" };\n");
}

fn alg_name(alg: Algebra) -> &'static str {
    match alg {
        Algebra::Kleene => "kleene",
        Algebra::Lukasiewicz => "lukasiewicz",
        Algebra::Bochvar => "bochvar",
    }
}


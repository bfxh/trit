//! 产物层：`expr.txt` / `truth.csv` / `truth.tritbin` / `lookup.c` / `direct.c` / `design.v`。
//!
//! 从 `main.rs` 拆出来：主流程只负责“算”，这里只负责“写”。拆的理由是
//! `main.rs` 已经顶到 783 行的模块预算，加一个后端就得先腾地方 —— 按仓库规矩
//! 「要腾地方就拆，别抬台账」。

use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde_json::{Value, json};
use trit_core::Algebra;
use trit_core::value::Ternary;

use crate::direct;

/// 产物后端：`table` 只出 `lookup.c`，`direct` 只出 `direct.c`，`both` 两份都出。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Backend {
    Table,
    Direct,
    Both,
}

impl Backend {
    pub(crate) fn parse(name: &str) -> Result<Self> {
        match name {
            "table" => Ok(Self::Table),
            "direct" => Ok(Self::Direct),
            "both" => Ok(Self::Both),
            other => bail!("未知的产物后端 {other:?}，可选：table / direct / both"),
        }
    }

    pub(crate) fn name(self) -> &'static str {
        match self {
            Self::Table => "table",
            Self::Direct => "direct",
            Self::Both => "both",
        }
    }

    pub(crate) const fn emits_table(self) -> bool {
        matches!(self, Self::Table | Self::Both)
    }

    pub(crate) const fn emits_direct(self) -> bool {
        matches!(self, Self::Direct | Self::Both)
    }
}

fn trit_i8(value: Ternary) -> i8 {
    match value {
        Ternary::True => 1,
        Ternary::Unknown => 0,
        Ternary::False => -1,
    }
}

pub(crate) fn truth_csv(vars: &[String], values: &[Ternary]) -> String {
    let mut text = String::new();
    text.push_str("code,");
    for var in vars {
        text.push_str(var);
        text.push(',');
    }
    text.push_str("verdict\n");
    for (code, value) in values.iter().enumerate() {
        text.push_str(&code.to_string());
        text.push(',');
        let mut rest = code;
        for _ in vars {
            let digit = rest % 3;
            rest /= 3;
            text.push_str(match digit {
                0 => "-1",
                1 => "0",
                _ => "1",
            });
            text.push(',');
        }
        text.push_str(match value {
            Ternary::False => "-1",
            Ternary::Unknown => "0",
            _ => "1",
        });
        text.push('\n');
    }
    text
}

/// `TRB2`：基 3 打包（5 trit/字节）+ GF(3) CRC-3 + 变量名表，见 `trb`。
fn tritbin(values: &[Ternary], alg: Algebra, names: &[String]) -> Result<Vec<u8>> {
    crate::trb::encode_named(values, alg, names)
}

pub(crate) fn lookup_c(vars: &[String], values: &[Ternary], alg: Algebra) -> String {
    let mut text = String::new();
    text.push_str("/* generated by trit build; 语义 = ");
    text.push_str(alg_name(alg));
    text.push_str(", 变量顺序 = ");
    text.push_str(&vars.join(","));
    text.push_str(" */\n");
    text.push_str("#include <stdint.h>\n\n");
    text.push_str("static const int8_t TRIT_TABLE[");
    text.push_str(&values.len().to_string());
    text.push_str("] = {\n");
    for chunk in values.chunks(12) {
        text.push_str("   ");
        for value in chunk {
            text.push_str(&format!(" {:>2},", trit_i8(*value)));
        }
        text.push('\n');
    }
    text.push_str("};\n\n");
    text.push_str(
        "int8_t trit_lookup(const int8_t *vars, unsigned nvars) {\n\
         \x20   unsigned code = 0;\n\
         \x20   for (unsigned i = 0; i < nvars; i++) code = code * 3u + (unsigned)(vars[i] + 1);\n\
         \x20   return TRIT_TABLE[code];\n\
         }\n",
    );
    text
}

fn alg_name(alg: Algebra) -> &'static str {
    match alg {
        Algebra::Kleene => "kleene",
        Algebra::Lukasiewicz => "lukasiewicz",
        Algebra::Bochvar => "bochvar",
    }
}

pub(crate) fn write_artifact(path: &Path, bytes: &[u8]) -> Result<String> {
    fs::write(path, bytes).with_context(|| format!("写 {} 失败", path.display()))?;
    Ok(crate::hex(crate::hash64(bytes)))
}

/// 写产物（两条链路共用）。
///
/// `expr` 只有 `.tri` 链路有（重写后的形态）；`direct` 后端需要它。
pub(crate) struct EmitRequest<'a> {
    pub out_dir: &'a Path,
    pub header: &'a str,
    pub vars: &'a [String],
    pub values: &'a [Ternary],
    pub algebra: Algebra,
    pub rail: Option<&'a str>,
    pub expr: Option<&'a trit_core::Expr>,
    pub backend: Backend,
}

pub(crate) fn emit_artifacts(request: EmitRequest<'_>) -> Result<serde_json::Map<String, Value>> {
    let EmitRequest {
        out_dir,
        header,
        vars,
        values,
        algebra,
        rail,
        expr,
        backend,
    } = request;
    let csv = truth_csv(vars, values);
    let blob = tritbin(values, algebra, vars)?;
    let mut artifacts = vec![
        ("expr.txt", header.as_bytes().to_vec()),
        ("truth.csv", csv.as_bytes().to_vec()),
        ("truth.tritbin", blob),
    ];
    if backend.emits_table() {
        artifacts.push(("lookup.c", lookup_c(vars, values, algebra).into_bytes()));
    }
    if backend.emits_direct() {
        let expr = expr.context(
            "--backend direct/both 目前只支持 .tri 源（Verilog 读入的设计没有表达式，无法直算）",
        )?;
        artifacts.push(("direct.c", direct::emit(expr, vars, algebra)?.into_bytes()));
    }
    if let Some(module) = rail {
        artifacts.push(("design.v", module.as_bytes().to_vec()));
    }
    let mut outputs = serde_json::Map::new();
    for (name, bytes) in artifacts {
        let hash = write_artifact(&out_dir.join(name), &bytes)?;
        outputs.insert(
            name.to_string(),
            json!({"bytes": bytes.len(), "hash": hash}),
        );
    }
    Ok(outputs)
}

//! GPU 导出（M2 遗留的 `--emit gpu`）：把真值表打成 WGSL 查表内核 + 2 bit/trit 位平面。
//!
//! 目标格式取 WGSL（仓里已有 `trit-gpu` 后端）：内核不重新推导三值语义，
//! 只做 `code → (pos, neg)` 取位——语义已经被构建期穷举复核固化进表里。
//! 导出的 `truth.gpu.bin` 是自描述布局，主机按 `truth_gpu.json` 上传缓冲即可。
//!
//! `truth.gpu.bin`：`TGPU` | version u8 | algebra u8 | nvars u8 | reserved u8
//! | len u32 | words u32 | pos\[words\] u32 LE | neg\[words\] u32 LE（头 16 字节）。

use trit_core::Algebra;
use trit_core::value::Ternary;

pub const MAGIC: &[u8; 4] = b"TGPU";
pub const VERSION: u8 = 1;
pub const HEADER: usize = 16;
pub const WORKGROUP: u32 = 64;

pub const KERNEL: &str = r#"// generated by trit-build --emit-gpu
// 输入：queries[i] = base-3 行号（0→False / 1→Unknown / 2→True）
// 表：truth.gpu.bin 的 pos/neg 位平面（每 trit 2 bit）
struct Params {
  len: u32,
  words: u32,
  _pad0: u32,
  _pad1: u32,
};

@group(0) @binding(0) var<uniform> params: Params;
@group(0) @binding(1) var<storage, read> queries: array<u32>;
@group(0) @binding(2) var<storage, read> table_pos: array<u32>;
@group(0) @binding(3) var<storage, read> table_neg: array<u32>;
@group(0) @binding(4) var<storage, read_write> out: array<i32>;

@compute @workgroup_size(64)
fn main(@builtin(global_invocation_id) id: vec3<u32>) {
  let index = id.x;
  if (index >= arrayLength(&queries)) {
    return;
  }
  let code = queries[index];
  if (code >= params.len) {
    out[index] = 0;
    return;
  }
  let word = code >> 5u;
  let bit = code & 31u;
  let pos = (table_pos[word] >> bit) & 1u;
  let neg = (table_neg[word] >> bit) & 1u;
  var value: i32 = 0;
  if (pos == 1u) {
    value = 1;
  } else if (neg == 1u) {
    value = -1;
  }
  out[index] = value;
}
"#;

/// 2 bit/trit 位平面 + 16 字节头。
pub fn table_bin(values: &[Ternary], nvars: usize, alg: Algebra) -> Vec<u8> {
    let words = values.len().div_ceil(32);
    let mut pos = vec![0u32; words];
    let mut neg = vec![0u32; words];
    for (code, value) in values.iter().enumerate() {
        let bit = 1u32 << (code % 32);
        match value {
            Ternary::True => pos[code / 32] |= bit,
            Ternary::False => neg[code / 32] |= bit,
            Ternary::Unknown => {}
        }
    }
    let mut out = Vec::with_capacity(HEADER + words * 8);
    out.extend_from_slice(MAGIC);
    out.push(VERSION);
    out.push(alg as u8);
    out.push(nvars as u8);
    out.push(0);
    out.extend_from_slice(&(values.len() as u32).to_le_bytes());
    out.extend_from_slice(&(words as u32).to_le_bytes());
    for word in &pos {
        out.extend_from_slice(&word.to_le_bytes());
    }
    for word in &neg {
        out.extend_from_slice(&word.to_le_bytes());
    }
    out
}

pub fn metadata(values: usize, nvars: usize, alg: Algebra) -> String {
    serde_json::json!({
        "format": "trit-gpu/1",
        "algebra": alg.as_str(),
        "nvars": nvars,
        "length": values,
        "words": values.div_ceil(32),
        "headerBytes": HEADER,
        "kernel": "truth.wgsl",
        "table": "truth.gpu.bin",
        "entry": "main",
        "workgroupSize": WORKGROUP,
        "decode": "i32: 1=True / 0=Unknown / -1=False；越界 code 输出 0",
        "bindings": {
            "0": "uniform Params { len, words, pad, pad }",
            "1": "storage read queries: array<u32>（base-3 行号）",
            "2": "storage read table_pos: array<u32>",
            "3": "storage read table_neg: array<u32>",
            "4": "storage read_write out: array<i32>",
        },
    })
    .to_string()
}

#[cfg(all(test, feature = "gpu"))]
mod tests {
    use super::*;
    use crate::bitplan;
    use trit_core::Parser;

    #[test]
    fn wgsl_kernel_parses_and_validates_without_a_gpu() {
        let module = naga::front::wgsl::parse_str(KERNEL).expect("truth.wgsl 必须能解析");
        naga::valid::Validator::new(
            naga::valid::ValidationFlags::all(),
            naga::valid::Capabilities::all(),
        )
        .validate(&module)
        .expect("truth.wgsl 必须通过 naga 校验");
    }

    fn unpack(bin: &[u8]) -> (usize, usize, Vec<u32>, Vec<u32>) {
        assert_eq!(&bin[..4], MAGIC);
        assert_eq!(bin[4], VERSION);
        let nvars = usize::from(bin[6]);
        let len = u32::from_le_bytes([bin[8], bin[9], bin[10], bin[11]]) as usize;
        let words = u32::from_le_bytes([bin[12], bin[13], bin[14], bin[15]]) as usize;
        assert_eq!(bin.len(), HEADER + words * 8);
        let pos: Vec<u32> = bin[HEADER..HEADER + words * 4]
            .as_chunks::<4>()
            .0
            .iter()
            .map(|b| u32::from_le_bytes(*b))
            .collect();
        let neg: Vec<u32> = bin[HEADER + words * 4..]
            .as_chunks::<4>()
            .0
            .iter()
            .map(|b| u32::from_le_bytes(*b))
            .collect();
        (nvars, len, pos, neg)
    }

    async fn run_gpu(
        len: usize,
        words: usize,
        pos: &[u32],
        neg: &[u32],
        queries: &[u32],
    ) -> Option<Vec<i32>> {
        use wgpu::util::DeviceExt;

        let instance = wgpu::Instance::new(wgpu::InstanceDescriptor::new_without_display_handle());
        let adapter = instance
            .request_adapter(&wgpu::RequestAdapterOptions::default())
            .await
            .ok()?;
        eprintln!("GPU adapter: {}", adapter.get_info().name);
        let limits = adapter.limits();
        let (device, queue) = adapter
            .request_device(&wgpu::DeviceDescriptor {
                required_limits: limits,
                ..Default::default()
            })
            .await
            .ok()?;

        let params = device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("truth-params"),
            contents: bytemuck::cast_slice(&[len as u32, words as u32, 0, 0]),
            usage: wgpu::BufferUsages::UNIFORM,
        });
        let query_buf = device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("truth-queries"),
            contents: bytemuck::cast_slice(queries),
            usage: wgpu::BufferUsages::STORAGE,
        });
        let pos_buf = device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("truth-pos"),
            contents: bytemuck::cast_slice(pos),
            usage: wgpu::BufferUsages::STORAGE,
        });
        let neg_buf = device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("truth-neg"),
            contents: bytemuck::cast_slice(neg),
            usage: wgpu::BufferUsages::STORAGE,
        });
        let out = device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("truth-out"),
            size: (queries.len() * 4) as u64,
            usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_SRC,
            mapped_at_creation: false,
        });
        let shader = device.create_shader_module(wgpu::ShaderModuleDescriptor {
            label: Some("truth-wgsl"),
            source: wgpu::ShaderSource::Wgsl(KERNEL.into()),
        });
        let layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: None,
            entries: &[
                wgpu::BindGroupLayoutEntry {
                    binding: 0,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Uniform,
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 1,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: true },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 2,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: true },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 3,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: true },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 4,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: false },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
            ],
        });
        let pipeline_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: None,
            bind_group_layouts: &[Some(&layout)],
            immediate_size: 0,
        });
        let pipeline = device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {
            label: Some("truth"),
            layout: Some(&pipeline_layout),
            module: &shader,
            entry_point: Some("main"),
            compilation_options: Default::default(),
            cache: None,
        });
        let bind = device.create_bind_group(&wgpu::BindGroupDescriptor {
            label: None,
            layout: &layout,
            entries: &[
                wgpu::BindGroupEntry {
                    binding: 0,
                    resource: params.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 1,
                    resource: query_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 2,
                    resource: pos_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 3,
                    resource: neg_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 4,
                    resource: out.as_entire_binding(),
                },
            ],
        });
        let mut encoder =
            device.create_command_encoder(&wgpu::CommandEncoderDescriptor { label: None });
        {
            let mut pass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor::default());
            pass.set_pipeline(&pipeline);
            pass.set_bind_group(0, &bind, &[]);
            pass.dispatch_workgroups((queries.len() as u32).div_ceil(WORKGROUP), 1, 1);
        }
        queue.submit([encoder.finish()]);
        let staging = device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("truth-staging"),
            size: (queries.len() * 4) as u64,
            usage: wgpu::BufferUsages::MAP_READ | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });
        let mut copy =
            device.create_command_encoder(&wgpu::CommandEncoderDescriptor { label: None });
        copy.copy_buffer_to_buffer(&out, 0, &staging, 0, (queries.len() * 4) as u64);
        queue.submit([copy.finish()]);
        let slice = staging.slice(..);
        slice.map_async(wgpu::MapMode::Read, |_| {});
        device
            .poll(wgpu::PollType::wait_indefinitely())
            .expect("poll");
        let mapped = slice.get_mapped_range().expect("map");
        let values = mapped
            .as_chunks::<4>()
            .0
            .iter()
            .map(|b| i32::from_le_bytes(*b))
            .collect();
        Some(values)
    }

    #[test]
    fn gpu_kernel_matches_the_truth_table() {
        for alg in [Algebra::Kleene, Algebra::Lukasiewicz, Algebra::Bochvar] {
            let expr = Parser::parse("(a & b) | (c => !a)").unwrap();
            let vars = expr.variables();
            let values = bitplan::table(&expr, &vars, alg, 1).unwrap();
            let bin = table_bin(&values, vars.len(), alg);
            let (nvars, len, pos, neg) = unpack(&bin);
            assert_eq!(nvars, vars.len());
            assert_eq!(len, values.len());
            assert_eq!(pos.len(), values.len().div_ceil(32));

            let mut queries: Vec<u32> = (0..values.len() as u32).collect();
            queries.push(values.len() as u32); // 越界：内核必须给 0 而不是越界读
            let Some(out) = pollster::block_on(run_gpu(len, pos.len(), &pos, &neg, &queries))
            else {
                eprintln!("没有可用 GPU adapter，跳过 GPU 对拍（表布局在 CPU 侧已校验）");
                return;
            };
            for (code, value) in values.iter().enumerate() {
                let expected = match value {
                    Ternary::True => 1,
                    Ternary::Unknown => 0,
                    Ternary::False => -1,
                };
                assert_eq!(out[code], expected, "{alg:?} code={code}");
            }
            assert_eq!(out[values.len()], 0, "越界 code 必须输出 0");
        }
    }
}

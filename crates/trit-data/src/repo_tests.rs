//! repo 单测。

    use super::*;
    use std::path::PathBuf;

    fn tmp(tag: &str) -> PathBuf {
        let p = std::env::temp_dir().join(format!("trit-repo-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&p);
        std::fs::create_dir_all(&p).unwrap();
        p
    }

    fn write(root: &Path, rel: &str, body: &str) {
        let p = root.join(rel);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, body).unwrap();
    }

    #[test]
    fn scans_units_with_language_imports_and_flags() {
        let root = tmp("scan");
        write(&root, "LICENSE", "MIT License\n");
        write(&root, "src/main.rs", "use std::io;\nfn main() {}\n");
        write(&root, "src/lib.py", "import os\n");
        write(&root, "tests/a_test.rs", "fn t() {}\n");
        write(&root, "generated/x.rs", "// generated by tool\nfn x() {}\n");
        write(&root, "target/skip.rs", "fn skip() {}\n");
        write(&root, "README.md", "# repo\n");
        let units = scan(&root).unwrap();
        assert!(units.iter().any(|u| u.path == "src/main.rs" && u.lang == "rust"));
        assert!(units
            .iter()
            .any(|u| u.path == "src/main.rs" && u.imports.contains(&"std::io".to_string())));
        assert!(units.iter().any(|u| u.path == "src/lib.py" && u.lang == "python"));
        assert!(units.iter().any(|u| u.path == "tests/a_test.rs" && u.is_test));
        assert!(units.iter().any(|u| u.path == "generated/x.rs" && u.generated));
        assert!(!units.iter().any(|u| u.path == "target/skip.rs"));
        assert!(units.iter().all(|u| u.license.as_deref() == Some("MIT")));
        let _ = std::fs::remove_dir_all(&root);
    }

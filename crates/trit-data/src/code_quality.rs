//! 代码质量规则（Stack v2 / StarCoder 风格的规则近似）。
//!
//! 检查行长、字母数字比例、注释比例、重复行与“自动生成”标记；
//! 只在代码占比达到阈值时使用，避免误伤自然语言。

#[derive(Debug, Clone, PartialEq)]
pub struct CodeQuality {
    pub long_line_ratio: f64,
    pub alnum_ratio: f64,
    pub comment_ratio: f64,
    pub repeat_line_ratio: f64,
    pub auto_generated: bool,
    pub ok: bool,
}

#[derive(Debug, Clone)]
pub struct Limits {
    pub max_long_line_ratio: f64,
    pub min_alnum_ratio: f64,
    pub max_comment_ratio: f64,
    pub max_repeat_line_ratio: f64,
    pub allow_auto_generated: bool,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            max_long_line_ratio: 0.2,
            min_alnum_ratio: 0.25,
            max_comment_ratio: 0.8,
            max_repeat_line_ratio: 0.3,
            allow_auto_generated: false,
        }
    }
}

pub fn check(text: &str) -> CodeQuality {
    check_with(text, &Limits::default())
}

pub fn check_with(text: &str, limits: &Limits) -> CodeQuality {
    let lines: Vec<&str> = text.lines().filter(|l| !l.trim().is_empty()).collect();
    let n = lines.len().max(1) as f64;
    let total = text.chars().count().max(1) as f64;
    let long = lines.iter().filter(|l| l.chars().count() > 1000).count() as f64 / n;
    let alnum = text.chars().filter(|c| c.is_alphanumeric()).count() as f64 / total;
    let comment = lines
        .iter()
        .filter(|l| {
            let t = l.trim();
            t.starts_with("//") || t.starts_with('#') || t.starts_with("/*") || t.starts_with('*')
        })
        .count() as f64
        / n;
    let mut seen = std::collections::BTreeSet::new();
    let repeat = lines.iter().filter(|l| !seen.insert(l.trim())).count() as f64 / n;
    let lower = text.to_lowercase();
    let auto = [
        "generated by",
        "do not edit",
        "auto-generated",
        "@generated",
        "this file is generated",
    ]
    .iter()
    .any(|k| lower.contains(k));
    let ok = !lines.is_empty()
        && long <= limits.max_long_line_ratio
        && alnum >= limits.min_alnum_ratio
        && comment <= limits.max_comment_ratio
        && repeat <= limits.max_repeat_line_ratio
        && (limits.allow_auto_generated || !auto);
    CodeQuality {
        long_line_ratio: long,
        alnum_ratio: alnum,
        comment_ratio: comment,
        repeat_line_ratio: repeat,
        auto_generated: auto,
        ok,
    }
}


//! code_quality 单测。

    use super::*;

    #[test]
    fn normal_code_passes() {
        let code = "fn main() {\n    let x = 1;\n    println!(\"{}\", x);\n}\n";
        let q = check(code);
        assert!(q.ok, "{q:?}");
        assert!(q.alnum_ratio > 0.3);
    }

    #[test]
    fn repeated_or_generated_code_fails() {
        let repeated = "let x = 1;\n".repeat(50);
        assert!(!check(&repeated).ok);
        let generated = "// generated by tool\nfn main() {}\n";
        let q = check(generated);
        assert!(q.auto_generated);
        assert!(!q.ok);
        assert!(!check("").ok);
    }

    #[test]
    fn long_lines_fail() {
        let long = "a".repeat(2000) + "\n";
        assert!(!check(&long).ok);
    }
